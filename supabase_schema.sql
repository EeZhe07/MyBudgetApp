
-- 1. Create Profiles Table (Public Profile Data)
create table public.profiles (
  id uuid references auth.users not null,
  email text,
  updated_at timestamp with time zone,
  primary key (id)
);

alter table public.profiles enable row level security;

create policy "Users can view own profile" on public.profiles
  for select using (auth.uid() = id);

create policy "Users can update own profile" on public.profiles
  for update using (auth.uid() = id);

-- 2. Create Assets Table
create table public.assets (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users not null,
  name text not null,
  balance numeric default 0,
  icon text,
  type text default 'cash', -- 'cash', 'bank', 'credit', etc.
  created_at timestamp with time zone default timezone('utc'::text, now())
);

alter table public.assets enable row level security;

create policy "Users can CRUD own assets" on public.assets
  for all using (auth.uid() = user_id);

-- 3. Create Categories Table
create table public.categories (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users not null,
  name text not null,
  icon text,
  type text not null, -- 'expense' or 'income'
  is_default boolean default false,
  created_at timestamp with time zone default timezone('utc'::text, now())
);

alter table public.categories enable row level security;

create policy "Users can CRUD own categories" on public.categories
  for all using (auth.uid() = user_id);

-- 4. Create Goals Table
create table public.goals (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users not null,
  title text not null,
  target_amount numeric not null,
  saved_amount numeric default 0,
  icon text,
  deadline date,
  background_image text,
  created_at timestamp with time zone default timezone('utc'::text, now())
);

alter table public.goals enable row level security;

create policy "Users can CRUD own goals" on public.goals
  for all using (auth.uid() = user_id);

-- 5. Create Transactions Table
create table public.transactions (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users not null,
  type text not null, -- 'expense', 'income', 'transfer'
  amount numeric not null,
  date timestamp with time zone not null,
  note text,
  
  -- Foreign Keys (Nullable because a transaction might allow custom text if we wanted, but let's link them)
  asset_id bigint references public.assets,
  category_id bigint references public.categories,
  goal_id bigint references public.goals,
  
  -- Transfer Specifics
  to_asset_id bigint references public.assets,

  created_at timestamp with time zone default timezone('utc'::text, now())
);

alter table public.transactions enable row level security;

create policy "Users can CRUD own transactions" on public.transactions
  for all using (auth.uid() = user_id);

-- 6. Create Budget Table
create table public.budget (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users not null,
  month text not null, -- '2023-10'
  amount numeric not null,
  created_at timestamp with time zone default timezone('utc'::text, now()),
  unique(user_id, month)
);

alter table public.budget enable row level security;

create policy "Users can CRUD own budget" on public.budget
  for all using (auth.uid() = user_id);

-- 7. Trigger to create Profile on Sign Up
create or replace function public.handle_new_user() 
returns trigger as $$
begin
  insert into public.profiles (id, email)
  values (new.id, new.email);
  return new;
end;
$$ language plpgsql security definer;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();
