drop table if exists public.profiles;

-- 1. Create Profiles Table
create table public.profiles (
  id uuid references auth.users not null,
  email text,
  updated_at timestamp with time zone,
  primary key (id)
);
alter table public.profiles enable row level security;
create policy "Users can view own profile" on public.profiles for select using (auth.uid() = id);
create policy "Users can update own profile" on public.profiles for update using (auth.uid() = id);

-- 2. Create Assets Table (ID as TEXT to support local timestamps/strings)
create table public.assets (
  id text not null primary key, -- Changed to TEXT
  user_id uuid references auth.users not null,
  name text not null,
  balance numeric default 0,
  icon text,
  type text default 'cash',
  created_at timestamp with time zone default timezone('utc'::text, now())
);
alter table public.assets enable row level security;
create policy "Users can CRUD own assets" on public.assets for all using (auth.uid() = user_id);

-- 3. Create Categories Table (ID as TEXT to support 'food', 'transport')
create table public.categories (
  id text not null primary key, -- Changed to TEXT
  user_id uuid references auth.users not null,
  name text not null,
  icon text,
  type text not null,
  is_default boolean default false,
  created_at timestamp with time zone default timezone('utc'::text, now())
);
alter table public.categories enable row level security;
create policy "Users can CRUD own categories" on public.categories for all using (auth.uid() = user_id);

-- 4. Create Goals Table (ID as TEXT)
create table public.goals (
  id text not null primary key, -- Changed to TEXT
  user_id uuid references auth.users not null,
  title text not null,
  target_amount numeric not null,
  saved_amount numeric default 0,
  icon text,
  deadline date,
  background_image text,
  created_at timestamp with time zone default timezone('utc'::text, now())
);
alter table public.goals enable row level security;
create policy "Users can CRUD own goals" on public.goals for all using (auth.uid() = user_id);

-- 5. Create Transactions Table
create table public.transactions (
  id text not null primary key, -- Changed to TEXT
  user_id uuid references auth.users not null,
  type text not null,
  amount numeric not null,
  date timestamp with time zone not null,
  note text,
  
  -- Foreign Keys (Match ID types)
  asset_id text references public.assets(id),
  category_id text references public.categories(id),
  goal_id text references public.goals(id),
  to_asset_id text references public.assets(id),

  created_at timestamp with time zone default timezone('utc'::text, now())
);
alter table public.transactions enable row level security;
create policy "Users can CRUD own transactions" on public.transactions for all using (auth.uid() = user_id);

-- 6. Create Budget Table
create table public.budget (
  id bigint generated by default as identity primary key, -- Budget ID doesn't matter locally usually
  user_id uuid references auth.users not null,
  month text not null,
  amount numeric not null,
  created_at timestamp with time zone default timezone('utc'::text, now()),
  unique(user_id, month)
);
alter table public.budget enable row level security;
create policy "Users can CRUD own budget" on public.budget for all using (auth.uid() = user_id);

-- 7. Trigger
create or replace function public.handle_new_user() 
returns trigger as $$
begin
  insert into public.profiles (id, email)
  values (new.id, new.email);
  return new;
end;
$$ language plpgsql security definer;

-- Re-create trigger (drop first if needed but usually okay on fresh tables)
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();
